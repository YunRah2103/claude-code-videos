def text_width(s):
    return sum(len(FONT[c][0]) for c in s) + len(s) - 1


class Grid:
    def __init__(self, w, h):
        self.w, self.h = w, h
        self.g = [[None]*w for _ in range(h)]

    def px(self, x, y, c):
        if 0 <= x < self.w and 0 <= y < self.h:
            self.g[y][x] = hexc(c) if c else None

    def rect(self, x0, y0, x1, y1, c):
        for y in range(y0, y1+1):
            for x in range(x0, x1+1):
                self.px(x, y, c)

    def disc(self, cx, cy, r, c):
        for y in range(int(cy-r)-1, int(cy+r)+2):
            for x in range(int(cx-r)-1, int(cx+r)+2):
                if (x-cx)**2 + (y-cy)**2 <= r*r + 0.5:
                    self.px(x, y, c)

    def text(self, x, y, s, c):
        for ch in s:
            rows = FONT[ch]
            for j, row in enumerate(rows):
                for i, b in enumerate(row):
                    if b == '1':
                        self.px(x+i, y+j, c)
            x += len(rows[0]) + 1

    def image(self, outline=True, oc=OUT):
        g = self.g
        if outline:
            src = [row[:] for row in g]
            g = [row[:] for row in g]
            for y in range(self.h):
                for x in range(self.w):
                    if src[y][x] is None:
                        for dx, dy in ((1,0),(-1,0),(0,1),(0,-1)):
                            nx, ny = x+dx, y+dy
                            if 0 <= nx < self.w and 0 <= ny < self.h and src[ny][nx] is not None:
                                g[y][x] = oc
                                break
        img = Image.new('RGBA', (self.w, self.h), (0, 0, 0, 0))
        img.putdata([c if c else (0, 0, 0, 0) for row in g for c in row])
        return img


def up(img, s):
    return img.resize((img.width*s, img.height*s), Image.NEAREST)



def outline(img, col=(26, 26, 46, 255)):
    """Add a 1-pixel dark outline around the opaque shape of a small RGBA sprite (4-neighbour)."""
    import numpy as np
    a = np.array(img)
    m = a[..., 3] > 0
    n = np.zeros_like(m)
    n[1:] |= m[:-1]; n[:-1] |= m[1:]; n[:, 1:] |= m[:, :-1]; n[:, :-1] |= m[:, 1:]
    a[n & ~m] = col
    return Image.fromarray(a, 'RGBA')
